// Render every landing design (or the ones named) with its sample.json into
// docs/landing-designs/<id>.html, so designs can be opened in a browser and
// reviewed without running the Worker.
//
//   npm run landing:preview            # all designs
//   npm run landing:preview -- shop    # one design
//   npm run landing:preview -- --dark  # preview dark mode
//
// Also prints validation errors for each design (same checks as npm test).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
require.extensions[".html"] = (module, filename) => { module.exports = readFileSync(filename, "utf8"); };

const { LANDING_DESIGNS } = await import("../src/landing-designs/index.ts");
const { renderTemplate, validateDesign } = await import("../src/landing-template.ts");
const { parseLandingContent, buildLandingView } = await import("../src/landing-view.ts");

const args = process.argv.slice(2);
const dark = args.includes("--dark");
const only = args.filter((a) => !a.startsWith("--"));

// Local placeholder "photos" so previews never load third-party images.
function placeholder(key) {
  let h = 0;
  for (const ch of key) h = (h * 31 + ch.charCodeAt(0)) % 360;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1000"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="hsl(${h},35%,55%)"/><stop offset="1" stop-color="hsl(${(h + 60) % 360},30%,32%)"/></linearGradient></defs><rect width="100%" height="100%" fill="url(#g)"/></svg>`;
  return "data:image/svg+xml;base64," + Buffer.from(svg).toString("base64");
}

const SAMPLE_POSTS = [
  { title: "Notes from this season's harvest", url: "/notes-from-the-harvest", date: "Oct 18, 2026" },
  { title: "The only guide you need to get started", url: "/getting-started-guide", date: "Oct 6, 2026" },
  { title: "Why we changed how we work", url: "/why-we-changed", date: "Sep 22, 2026" },
];

export function previewHead({ title, accent, customCss = "" }) {
  const theme = dark ? "dark" : "light";
  return [
    `<title>${title.replace(/</g, "&lt;")}</title>`,
    `<script>document.documentElement.dataset.theme=${JSON.stringify(theme)}</script>`,
    accent ? `<style>:root{--accent:${accent}}</style>` : "",
    customCss ? `<style>${customCss}</style>` : "",
  ].join("\n");
}

mkdirSync(new URL("../docs/landing-designs/", import.meta.url), { recursive: true });
let failed = false;
for (const design of LANDING_DESIGNS) {
  if (only.length && !only.includes(design.id)) continue;
  const errors = validateDesign(design.id, design.template, design);
  if (errors.length) {
    failed = true;
    console.error(`✗ ${design.id}\n  - ${errors.join("\n  - ")}`);
  }
  const sample = JSON.parse(readFileSync(new URL(`../src/landing-designs/${design.id}/sample.json`, import.meta.url), "utf8"));
  const content = parseLandingContent(sample.content);
  const site = sample.site ?? {};
  const view = buildLandingView(content, {
    design_id: design.id,
    title: site.title ?? "Sample site",
    footer_name: site.footer_name ?? site.title ?? "Sample site",
    blog_url: "/blog",
    avatar_url: site.avatar_key ? placeholder(site.avatar_key) : null,
    nav: site.nav ?? [],
    social: site.social ?? [],
    posts: site.posts ?? SAMPLE_POSTS,
    body_end_html: "",
    head_html: previewHead({ title: site.title ?? design.label, accent: site.accent, customCss: site.custom_css }),
    media_url: placeholder,
    year: 2026,
  });
  const html = `<!-- GENERATED by scripts/landing-preview.mjs from src/landing-designs/${design.id}/. Do not edit. -->\n` +
    renderTemplate(design.template, view);
  const out = new URL(`../docs/landing-designs/${design.id}${dark ? "-dark" : ""}.html`, import.meta.url);
  writeFileSync(out, html);
  if (!errors.length) console.log(`✓ ${design.id} → docs/landing-designs/${design.id}${dark ? "-dark" : ""}.html`);
}
process.exit(failed ? 1 : 0);
